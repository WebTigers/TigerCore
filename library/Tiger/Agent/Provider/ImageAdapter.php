/**
 * Tiger_Agent_Provider_ImageAdapter — the contract an adapter implements if its provider can DRAW.
 *
 * A SIBLING interface, not a method on Tiger_Agent_Provider_Adapter, and the distinction is
 * deliberate (TIGER-96). `complete()` is text-in/text-out; generation is prompt+params → bytes, a
 * different shape that has no business being squeezed through it. Making it a separate interface
 * also means "can this adapter draw?" is answerable with `instanceof` — a stronger, compile-time-ish
 * signal than a method every adapter must stub and that might return null.
 *
 * Capability is TWO questions, both of which must be yes:
 *   1. Does the ADAPTER implement this interface?            → `instanceof`
 *   2. Can the chosen MODEL generate images?                 → Factory::supportsImageGeneration()
 * An adapter may implement this while the model selected in it cannot draw (OpenAI serves both
 * kinds), so neither check substitutes for the other.
 *
 * This is independent of vision. Vision READS images, generation WRITES them, and a model may have
 * either without the other — so `supportsVision()` and `supportsImageGeneration()` are separate
 * probes and must stay that way.
 *
 * @api
 */
interface Tiger_Agent_Provider_ImageAdapter
{
    /**
     * Generate one or more images.
     *
     * The return is NORMALISED so callers never branch on provider. Providers disagree about almost
     * everything here — URL vs base64, one image vs many, which parameters they echo — and resolving
     * that is the adapter's job, not the caller's.
     *
     * `params` must report what was ACTUALLY used, including anything the provider chose rather than
     * the caller: a seed it picked, a size it snapped to, a model alias it resolved. That echo is
     * what makes a later refinement reproducible; an image whose real parameters were never recorded
     * cannot be iterated on, only regenerated by luck.
     *
     * @param  string $prompt  the plain-English description
     * @param  array  $options {
     *     negative_prompt?: string,   what to avoid, where the provider supports it
     *     size?:            string,   e.g. '1024x1024' — adapters snap to their nearest legal value
     *     n?:               int,      how many images (default 1)
     *     seed?:            int,      for reproducibility, where supported
     *     reference?:       array{mime:string,data:string}   a base64 image to steer from (img2img)
     * }
     * @param  string $model   the model id to call
     * @param  string $apiKey  the org's BYO key (decrypted)
     * @return array{
     *     images: array<int,array{mime:string,data:string}>,   base64, never a URL the caller must fetch
     *     params: array<string,mixed>                          what was actually used
     * }
     * @throws RuntimeException on a transport/API failure, or if the provider refused the prompt
     */
    public function generateImage($prompt, array $options, $model, $apiKey);
}
